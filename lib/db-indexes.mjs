export async function ensureAllIndexes(db, batchSize = 12) {
  for (let i = 0; i < INDEX_SPECS.length; i += batchSize) {
    await Promise.all(
      INDEX_SPECS.slice(i, i + batchSize).map((spec) =>
        db.collection(spec.collection).createIndex(spec.keys, spec.options),
      ),
    );
  }
  return INDEX_SPECS.length;
}
